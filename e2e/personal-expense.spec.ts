//   personal は店長(store_manager) のみ起票可能、目的・参加者が必須、
//   通知文言・支払ラベルが「給与振込」系に切り替わる。
//
// 認証配下のフローのため、Firebase Auth + Supabase の認証モック基盤が必要。
