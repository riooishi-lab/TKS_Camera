		// 1. expense_type=personal のレシート詳細を開く
		// 2. ヘッダのステータスバッジ横に「店長立替」バッジ
		// 3. 「申請区分」行に「店長立替（給与同時振込）」と表示
		// 4. 「支払済にする」ボタンが「給与振込で支給済にする」に変わる
